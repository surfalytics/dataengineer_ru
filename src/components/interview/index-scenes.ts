export type Node = { id: string; x: number; y: number; width: number; label: string; detail?: string };
export type Edge = { from: string; to: string; d?: string };
export type Frame = { on: string[]; title: string; note: string; via?: [string,string]; token?: string; query?: string };
export type Scene = { query: string; description: string; nodes: Node[]; edges: Edge[]; frames: Frame[] };

const box = (id: string, x: number, y: number, width: number, label: string, detail?: string): Node =>
  ({ id, x, y, width, label, detail });
const links = (...pairs: [string,string][]): Edge[] => pairs.map(([from,to]) => ({from,to}));
const frame = (on: string[], title: string, note: string, via?: [string,string], token?: string): Frame =>
  ({on,title,note,via,token});

function btree(): Scene {
  const nodes = [
    box('root',206,29,112,'Корень','50'),
    box('left',101,100,108,'Развилка','30'), box('right',311,100,108,'Развилка','70'),
    box('l0',50,178,92,'Лист','10 · 22'), box('l1',153,178,92,'Лист','30 · 42'),
    box('r0',259,178,92,'Лист','50 · 62'), box('r1',362,178,92,'Лист','70 · 75'),
    box('h1',145,262,137,'Таблица · (7, 3)','42 · 18 °C'), box('h2',335,262,137,'Таблица · (9, 1)','75 · 21 °C'),
  ];
  const frames: Frame[] = [];
  for (const key of [42, 75]) {
    const lower = key < 50;
    const node = lower ? 'left' : 'right';
    const leaf = lower ? 'l1' : 'r1';
    const heap = lower ? 'h1' : 'h2';
    const boundary = lower ? 30 : 70;
    const trace = [
      frame(['root'],'Корень',`Сравниваем искомый ключ ${key} с границей 50.`),
      frame(['root',node],'Выбор ветки',lower ? '42 меньше 50. Спускаемся в левое поддерево.' : '75 больше 50. Спускаемся в правое поддерево.', ['root',node],String(key)),
      frame(['root',node,leaf],'Листовая страница',`${key} больше ${boundary}. В правом листе этой ветки находим запись с ключом ${key}.`, [node,leaf],String(key)),
      frame(['root',node,leaf,heap],'Переход в таблицу',`Из листа берём TID ${lower ? '(7, 3)' : '(9, 1)'}. По этому адресу читаем строку и проверяем её видимость.`,[leaf,heap],'TID'),
      frame([leaf,heap],'Найдена строка',`Ключ ${key} найден. Листья в соседних ветках для этого поиска читать не пришлось.`),
    ];
    frames.push(...trace.map(f=>({...f,query:`WHERE k = ${key}`})));
  }
  return { query:'WHERE k = 42',description:'Два поиска в одном дереве: 42 идёт через левое поддерево, 75 — через правое.',nodes,
    edges:links(['root','left'],['root','right'],['left','l0'],['left','l1'],['right','r0'],['right','r1'],['l1','h1'],['r1','h2']), frames };
}

