#!/usr/bin/env python3
"""Глава 18: стратегия при владельце private equity. Usage: ch18_diagrams.py [name ...]  (no args = all)"""
from excb import N, E, Z, T, run_all

D = {}

# Главная схема: диагноз и политика (документ 18-1), пять пар
cols = [
    ("Расходы на персонал:\n+15% и +18% в год,\nштат: +7% и +9%",
     "N-1 backfill и один\nPrincipal на бизнес-\nюнит: −5% в год"),
    ("Владелец, скорее\nвсего, потребует\nсокращений, цифр нет",
     "Ждём цели по R&D,\nне планируем\nсокращения заранее"),
    ("Инфраструктура:\n+4-5% в год,\nрезервов мало",
     "Инфраструктура не\nболее +5% в год,\nразово −3%"),
    ("Поддержка старых\nфункций дорога,\nметрик нет",
     "Рабочая группа ищет\nфункции с самой\nбольшой нагрузкой"),
    ("Найм в дорогих\nрегионах: 1% роста\nрасходов",
     "География найма не\nменяется: нет\nсогласия партнёров"),
]
items = [Z("Диагноз", -20, -40, 1640, 210), Z("Политика", -20, 250, 1640, 230)]
edges = []
for i, (d, p) in enumerate(cols):
    items.append(N(f"d{i}", d, i * 325, 20, "y", 300, 120))
    items.append(N(f"p{i}", p, i * 325, 320, "g" if i != 1 else "n", 300, 120))
    edges.append(E(f"d{i}", f"p{i}"))
D["ch18-policy-map"] = dict(items=items, edges=edges)

# Рис. 18-2, 18-3: P&L Zendesk, рост статей расходов против выручки
D["ch18-zendesk"] = dict(items=[
    N("rev", "Выручка Zendesk:\n6 месяцев 2022\nк тому же периоду 2021", 0, 170, "p", 320, 120),
    N("sm", "Sales and Marketing:\nрастёт медленнее\nвыручки", 520, 0, "g", 360, 110),
    N("rd", "R&D: растёт примерно\nв 1,5 раза быстрее\nвыручки", 520, 170, "r", 360, 120),
    N("ga", "G&A: растёт больше\nчем в 2 раза быстрее\nвыручки", 520, 340, "r", 360, 120),
    N("cut", "Сокращения:\nноябрь 2022 и май 2023,\nупор на G&A", 1080, 170, "y", 340, 120),
], edges=[E("rev", "sm"), E("rev", "rd"), E("rev", "ga"), E("rd", "cut"), E("ga", "cut")])

# Рис. 18-7 - 18-10: stocks и flows модели состава по уровням
lv = []
ed = []
for n in range(1, 5):
    x = (n - 1) * 400
    lv.append(N(f"c{n}", "Кандидаты\n(хватает всегда)", x, 0, "n", 280, 90))
    lv.append(N(f"l{n}", f"SWE{n}" + ("\n(потолок: 20 человек)" if n == 4 else ""), x, 220, "r" if n == 4 else "p", 280, 100))
    lv.append(N(f"u{n}", f"Ушли с SWE{n}" + ("\n(заменяем на SWE1)" if n == 1 else ""), x, 450, "n", 280, 100 if n == 1 else 80))
    ed += [E(f"c{n}", f"l{n}"), E(f"l{n}", f"u{n}")]
    if n < 4:
        ed.append(E(f"l{n}", f"l{n + 1}"))
    if n > 1:
        ed.append(E(f"u{n}", f"l{n - 1}", dashed=True))
lv.append(T("Сплошные стрелки: найм снаружи, повышение вверх, уход. Пунктир: backfill на уровень ниже.", 0, 600, 18))
D["ch18-stocks-flows"] = dict(items=lv, edges=ed)

# Рис. 18-11 - 18-14: что даёт каждая политика (50-й раунд, наш запуск)
D["ch18-policy-steps"] = dict(items=[
    N("s1", "1. Замена на том же уровне\nSWE4: 246 человек · SWE1 к SWE4 = 0,08", 0, 0, "r", 780, 100),
    N("s2", "2. Замена на уровень ниже (N-1)\nSWE4: 100 человек · SWE1 к SWE4 = 0,80", 0, 230, "q", 780, 100),
    N("s3", "3. N-1 и найма нет\nSWE4: 60 человек · SWE1 к SWE4 = 1,15", 0, 460, "y", 780, 100),
    N("s4", "4. N-1, найма нет, потолок SWE4 = 20\nSWE4: 20 человек · SWE1 к SWE4 = 3,65", 0, 690, "g", 780, 100),
    T("Цель: SWE1 к SWE4 около 5 к 1", 150, 840, 20, "#2f9e44"),
], edges=[E("s1", "s2", "+ N-1"), E("s2", "s3", "найма нет"), E("s3", "s4", "+ потолок")])

if __name__ == "__main__":
    run_all(D)
