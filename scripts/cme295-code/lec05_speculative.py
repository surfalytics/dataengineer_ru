"""Спекулятивное декодирование: итоговые вероятности токенов равны вероятностям целевой модели."""
import numpy as np

rng = np.random.default_rng(0)
T = np.array([0.50, 0.30, 0.15, 0.05])      # целевая модель: вероятности 4 токенов
D = np.array([0.25, 0.25, 0.25, 0.25])      # черновая модель: думает иначе
N = 200_000

d = rng.choice(4, size=N, p=D)              # черновая модель предлагает токен
u = rng.random(N)
принят = u < np.minimum(1, T[d] / D[d])     # принимаем с вероятностью min(1, T/D)
остаток = np.maximum(T - D, 0)
остаток = остаток / остаток.sum()           # остаточное распределение
замена = rng.choice(4, size=N, p=остаток)   # при отказе берём токен отсюда
итог = np.where(принят, d, замена)

частоты = np.bincount(итог, minlength=4) / N
print("целевая модель  :", T)
print("черновая модель :", D)
print("метод, частоты  :", np.round(частоты, 2))
print("доля принятых   :", round(принят.mean(), 3), "= сумма min(T, D) =", round(np.minimum(T, D).sum(), 3))
