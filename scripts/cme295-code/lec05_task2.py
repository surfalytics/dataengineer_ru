"""Задача 2: размер KV-кэша для контекста в 32 000 токенов."""
слоёв, голов, d_head, байт = 80, 64, 128, 2
контекст = 32_000

for имя, kv_голов in [("MHA, 64 пары", 64), ("GQA, 8 пар", 8), ("MQA, 1 пара", 1)]:
    на_токен = 2 * слоёв * kv_голов * d_head * байт
    print(f"{имя:13s} {на_токен / 1024:6.0f} КБ на токен, {на_токен * контекст / 1e9:6.1f} ГБ на запрос")
