"""Размер KV-кэша: MHA, GQA, MLA и потери памяти без PagedAttention."""
import math
import numpy as np

слоёв, голов, d_head = 32, 32, 128
байт = 2                                       # fp16


def на_токен(kv_голов):                         # key и value, во всех слоях
    return 2 * слоёв * kv_голов * d_head * байт


варианты = {
    "MHA: 32 пары key и value": на_токен(голов),
    "GQA: 8 пар": на_токен(8),
    "GQA: 2 пары": на_токен(2),
    "MLA: один вектор 256 на слой": слоёв * 256 * байт,
}
контекст = 8192
print(f"KV-кэш одного запроса при контексте {контекст} токенов:")
for имя, b in варианты.items():
    print(f"  {имя:30s} {b / 1024:7.0f} КБ на токен, {b * контекст / 1e9:5.2f} ГБ на запрос")
print(f"экономия GQA при h=24, g=2: {1 - 2 / 24:.1%}")

# PagedAttention: сколько запросов влезет в 40 ГБ под KV-кэш
rng = np.random.default_rng(1)
макс = 4096                                    # провайдер резервирует максимум на каждый запрос
длины = np.clip(rng.lognormal(6.6, 0.7, 10_000), 20, макс).astype(int)   # реальные длины
B = 16                                         # размер блока
бюджет = 40e9 / на_токен(8)                    # сколько токенов поместится (GQA с 8 парами)
резерв = макс                                  # резервируем максимум
блоками = np.ceil(длины / B) * B               # берём по блокам по 16 токенов
print(f"\nсредняя длина запроса: {длины.mean():.0f} токенов из {макс}")
print(f"влезает запросов с резервом максимума: {бюджет / резерв:.0f}")
print(f"влезает запросов с блоками по {B}: {бюджет / блоками.mean():.0f}")
print(f"потерянная память с блоками: {1 - длины.mean() / блоками.mean():.1%}")
