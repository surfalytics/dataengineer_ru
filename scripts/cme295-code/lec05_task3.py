"""Задача 3: сколько токенов даёт один проход целевой модели и какой выигрыш во времени."""
import numpy as np

alpha, k = 0.8, 4          # вероятность принять токен, длина черновика
c = 0.1                    # шаг черновой модели стоит 10% шага целевой

ожидание = (1 - alpha ** (k + 1)) / (1 - alpha)   # принятые токены + один токен от целевой модели
время = k * c + 1                                  # k шагов черновика + один проход целевой
print(f"по формуле: {ожидание:.2f} токена за проход, время {время:.1f}, выигрыш в {ожидание / время:.2f} раза")

rng = np.random.default_rng(3)
всего = 0
for _ in range(100_000):
    принято = 0
    while принято < k and rng.random() < alpha:
        принято += 1
    всего += принято + 1                           # +1: целевая модель всегда даёт следующий токен
print(f"симуляция : {всего / 100_000:.2f} токена за проход")
