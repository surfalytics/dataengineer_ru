"""Задача 1: хватит ли 80 ГБ на GPU для обучения модели на 70 млрд параметров с ZeRO."""
import math

P, GPU = 70e9, 80e9
w, g, o = 2, 2, 8                       # байт на параметр: веса, градиенты, состояние Adam


def память(стадия, N):
    доли = {1: (w, g, o / N), 2: (w, g / N, o / N), 3: (w / N, g / N, o / N)}[стадия]
    return P * sum(доли)


for стадия in (1, 2, 3):
    # пол: что остаётся на каждой GPU, сколько бы GPU мы ни взяли
    пол = P * {1: w + g, 2: w, 3: 0}[стадия]
    if пол >= GPU:
        print(f"ZeRO-{стадия}: не хватит при любом числе GPU (только веса и градиенты дают {пол / 1e9:.0f} ГБ)")
        continue
    N = 1
    while память(стадия, N) > GPU:
        N += 1
    print(f"ZeRO-{стадия}: хватит {N} GPU, на каждой {память(стадия, N) / 1e9:.1f} ГБ")
