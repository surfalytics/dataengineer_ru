"""Roofline: когда умножение матрицы упирается в память, а когда в вычисления."""
FLOPS = 1000e12      # порядок величины: 1000 TFLOPS
BW = 1e12            # порядок величины: 1 ТБ/с между HBM и вычислительными блоками
d = 8192             # размер квадратной матрицы весов, байт на число: 2 (fp16)

ridge = FLOPS / BW
print(f"ridge point: {ridge:.0f} FLOPs на байт\n")
print("токенов в пачке | FLOPs/байт | время вычислений | время чтения | узкое место")
for B in [1, 8, 64, 512, 1024, 4096]:
    flops = 2 * d * d * B                      # умножаем матрицу весов на B векторов
    байт = 2 * d * d + 2 * d * B * 2           # веса читаем один раз + входы и выходы
    t_calc, t_mem = flops / FLOPS, байт / BW
    узкое = "память" if t_mem > t_calc else "вычисления"
    print(f"{B:15d} | {flops / байт:10.1f} | {t_calc * 1e6:13.1f} мкс | {t_mem * 1e6:9.1f} мкс | {узкое}")
