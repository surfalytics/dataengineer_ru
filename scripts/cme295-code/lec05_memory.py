"""Сколько памяти нужно для обучения модели на 100 млрд параметров и как её делит ZeRO."""
import math

P = 100e9            # параметры модели
GPU = 141            # ГБ памяти у H200
N = 64               # число GPU в группе данных
веса, градиенты, оптимизатор = 2, 2, 8   # байт на параметр: fp16, fp16, Adam (два числа fp32)

print(f"только веса в fp16: {P * веса / 1e9:.0f} ГБ, одна GPU даёт {GPU} ГБ")
всего = P * (веса + градиенты + оптимизатор) / 1e9
print(f"веса + градиенты + Adam: {всего:.0f} ГБ, минимум GPU: {math.ceil(всего / GPU)} (без активаций)")
print()
print(f"память на одну GPU при {N} GPU, ГБ (без активаций):")
стадии = {
    "без ZeRO (копия на каждой)": (веса, градиенты, оптимизатор),
    "ZeRO-1: делим оптимизатор": (веса, градиенты, оптимизатор / N),
    "ZeRO-2: + градиенты": (веса, градиенты / N, оптимизатор / N),
    "ZeRO-3: + параметры": (веса / N, градиенты / N, оптимизатор / N),
}
for имя, (w, g, o) in стадии.items():
    print(f"  {имя:28s} {P * (w + g + o) / 1e9:7.1f}")
