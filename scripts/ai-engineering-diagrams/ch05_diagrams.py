def bars(prefix, vals, labels, x0, base, hfun, bw=60, gap=20, kinds=None, vlabels=None, lsize=16):
    """Column chart from rectangles. hfun(v) -> height in px. Returns items."""
    items = []
    for i, (v, lab) in enumerate(zip(vals, labels)):
        x = x0 + i * (bw + gap)
        h = max(hfun(v), 0)
        k = (kinds or {}).get(i, "p")
        if h:
            items.append(N(f"{prefix}{i}", "", x, base - h, k, bw, h))
        vl = vlabels[i] if vlabels else str(v)
        items.append(T(vl, x + bw / 2 - 5.5 * len(vl), base - h - 30, 20, "#495057"))
        items.append(T(lab, x - 2, base + 10, lsize, "#495057"))
    return items


