# ---------------------------------------------------------------- Fig 5-6: CoT gain
def _cot_panel(prefix, title, x0, std_cot, prior):
    labels = ["LaMDA\n137B", "GPT\n175B", "PaLM\n540B"]
    items = [T(title, x0, -85, 20, "#495057")]
    base = 330
    sc = 3.0
    for i, (s, c) in enumerate(std_cot):
        xs = x0 + i * 150
        items.append(N(f"{prefix}s{i}", "", xs, base - s * sc, "n", 55, s * sc))
        items.append(N(f"{prefix}c{i}", "", xs + 62, base - c * sc, "p", 55, c * sc))
        items.append(T(str(s), xs + 27 - 5.5 * len(str(s)), base - s * sc - 28, 18, "#495057"))
        items.append(T(str(c), xs + 62 + 27 - 5.5 * len(str(c)), base - c * sc - 28, 18, "#1971c2"))
        items.append(T(labels[i], xs + 4, base + 10, 16, "#495057"))
    items.append(N(f"{prefix}pr", "", x0 + 450, base - prior * sc, "q", 40, 10))
    items.append(T(f"{prior}", x0 + 453, base - prior * sc - 28, 18, "#e8590c"))
    items.append(T("оранжевый маркер: лучший прежний результат без CoT", x0, -50, 16, "#e8590c"))
    return items


