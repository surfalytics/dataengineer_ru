def vbars(prefix, vals, labels, x0, base, scale, bw=60, gap=20, kind="p", fmt=None, hl=None, lsize=16, vsize=20):
    """Column chart from rectangles. Returns items."""
    items = []
    fmt = fmt or (lambda v: str(v))
    for i, (v, lab) in enumerate(zip(vals, labels)):
        x = x0 + i * (bw + gap)
        h = max(v * scale, 3)
        k = "g" if hl == i else kind
        items.append(N(f"{prefix}{i}", "", x, base - h, k, bw, h))
        t = fmt(v)
        if t:
            items.append(T(t, x + bw / 2 - 5.5 * len(t), base - h - 30, vsize, GRAY))
        if lab:
            items.append(T(lab, x - 4, base + 10, lsize, GRAY))
    return items


def hbars(prefix, vals, labels, x0, y0, scale, bh=44, pitch=64, kind="p", fmt=None, lx=None, hl=None):
    items = []
    fmt = fmt or (lambda v: str(v))
    for i, (v, lab) in enumerate(zip(vals, labels)):
        y = y0 + i * pitch
        k = "g" if hl == i else kind
        items.append(T(lab, lx if lx is not None else x0 - 230, y + 10, 20, GRAY))
        items.append(N(f"{prefix}{i}", "", x0, y, k, v * scale, bh))
        items.append(T(fmt(v), x0 + v * scale + 12, y + 10, 20, GRAY))
    return items


