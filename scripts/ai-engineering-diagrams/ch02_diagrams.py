def fmt(v):
    s = f"{v:.1f}" if v != int(v) else str(int(v))
    return s.replace(".", ",")


def hbars(prefix, rows, x0, y0, scale, labw, bh=40, gap=12, fs=20):
    """Horizontal bar chart. rows: (label, value, kind[, text]). Returns items."""
    items = []
    for i, r in enumerate(rows):
        lab, v, k = r[:3]
        txt = r[3] if len(r) > 3 else fmt(v)
        y = y0 + i * (bh + gap)
        w = max(v * scale, 4)
        items.append(T(lab, x0, y + 8, fs, GRAY))
        items.append(N(f"{prefix}{i}", "", x0 + labw, y, k, w, bh))
        items.append(T(txt, x0 + labw + w + 12, y + 8, fs, GRAY))
    return items


def vbars(prefix, vals, labels, x0, base, scale, bw=70, gap=24, kinds=None, texts=None, off=0, fs=20):
    """Column chart. Height = (v - off) * scale."""
    items = []
    for i, (v, lab) in enumerate(zip(vals, labels)):
        x = x0 + i * (bw + gap)
        h = max((v - off) * scale, 4)
        k = kinds[i] if kinds else "p"
        t = texts[i] if texts else fmt(v)
        items.append(N(f"{prefix}{i}", "", x, base - h, k, bw, h))
        if t:
            items.append(T(t, x + bw / 2 - 5.5 * len(t), base - h - 30, fs, GRAY))
        if lab:
            items.append(T(lab, x + bw / 2 - 5 * len(lab), base + 10, 17, GRAY))
    return items


