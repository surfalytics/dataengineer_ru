# ---------------------------------------------------------------- own: compound errors
def vbars(prefix, vals, labels, x0, base, scale, bw=90, gap=40, kind="p", hl=None):
    items = []
    for i, (v, lab) in enumerate(zip(vals, labels)):
        x = x0 + i * (bw + gap)
        h = max(v * scale, 4)
        items.append(N(f"{prefix}{i}", "", x, base - h, "r" if hl == i else kind, bw, h))
        items.append(T(str(v).replace(".", ",") + "%", x + bw / 2 - 12 * len(str(v)) / 2 - 8, base - h - 32, 20, "#495057"))
        items.append(T(lab, x - 6, base + 10, 18, "#495057"))
    return items

