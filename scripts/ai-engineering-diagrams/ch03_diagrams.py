def vbars(prefix, vals, labels, x0, base, scale, bw=60, gap=20, kind="p", hl=None):
    """Column chart from rectangles. Returns items."""
    items = []
    for i, (v, lab) in enumerate(zip(vals, labels)):
        x = x0 + i * (bw + gap)
        h = max(v * scale, 0)
        if h:
            items.append(N(f"{prefix}{i}", "", x, base - h, "r" if hl == i else kind, bw, h))
        items.append(T(str(v), x + bw / 2 - 8 * len(str(v)) / 2 - 2, base - h - 30, 20, "#495057"))
        items.append(T(lab, x - 4, base + 10, 16, "#495057"))
    return items

