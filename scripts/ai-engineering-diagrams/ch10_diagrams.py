# ---------------------------------------------------------------- architecture, step by step
def arch(step, full=False):
    """Architecture of the app. step: 1 context, 2 guardrails, 3 router, 4 gateway, 5 cache, 6 write actions.
    New blocks of the step are orange; in the full picture blocks are coloured by step."""
    new = {1: {"ctx", "ro", "db"}, 2: {"ig", "scoring", "og"}, 3: {"routing"}, 4: set(),
           5: {"c1", "c2"}, 6: {"wa"}}[step]
    has_ig, has_routing, has_cache, has_wa, gateway = step >= 2, step >= 3, step >= 5, step >= 6, step >= 4

    def k(i, base):
        return base if full else ("q" if i in new else "p")

    def t(text, num):
        return f"{num}. {text}" if full else text

    models = (["routing"] if has_routing else []) + ["gen"] + (["scoring"] if has_ig else [])
    zone_title = t("Model gateway", 3) if gateway else "Model API"
    items = [Z(zone_title, 1160, -70, 260, len(models) * 110 + 70),  # zone first: it must lie under the boxes
             N("req", "Запрос\nпользователя", 0, 0, "n", 220, 80),
             N("ans", "Ответ\nпользователю", 0, 440, "n", 220, 80),
             N("ctx", t("Сбор контекста\n(RAG, tools,\nquery rewriting)", 1), 600, 0, k("ctx", "p"), 220, 100),
             N("ro", t("Read-only\nactions\n(поиск, SQL, web)", 1), 460, -300, k("ro", "p"), 220, 100),
             N("db", t("Базы данных\n(документы,\nтаблицы, история)", 1), 720, -300, k("db", "p"), 230, 100)]
    edges = []
    labels = {"routing": t("Routing\n(router)", 3), "gen": "Generation", "scoring": t("Scoring\n(scorers)", 2)}
    colors = {"routing": k("routing", "pu"), "gen": "p", "scoring": k("scoring", "r")}
    for i, m in enumerate(models):
        items.append(N(m, labels[m], 1180, i * 110, colors[m], 220, 70))
    for a, b in zip(models, models[1:]):
        edges.append(E(a, b))
    if has_ig:
        items.append(N("ig", t("Input\nguardrails\n(PII, injection)", 2), 880, 0, k("ig", "r"), 220, 100))
        items.append(N("og", t("Output\nguardrails\n(безопасность,\nформат)", 2), 860, 440, k("og", "r"), 240, 110))
    if has_cache:
        items.append(N("c1", t("Кэш\nзапросов\n(exact, semantic)", 4), 300, 0, k("c1", "y"), 220, 100))
        items.append(N("c2", t("Кэш поиска", 4), 600, -150, k("c2", "y"), 220, 70))
    if has_wa:
        items.append(N("wa", t("Write actions\n(письмо, заказ)", 5), 1200, 440, k("wa", "g"), 220, 80))
    # request path
    first = "c1" if has_cache else "ctx"
    edges.append(E("req", first))
    if has_cache:
        edges.append(E("c1", "ctx", "miss"))
        edges.append(E("c1", "ans", "hit", dashed=True))
    # context sources
    src_to = "c2" if has_cache else "ctx"
    edges += [E("ro", src_to), E("db", src_to)]
    if has_cache:
        edges.append(E("c2", "ctx"))
    # context -> model
    edges.append(E("ctx", "ig" if has_ig else models[0]))
    if has_ig:
        edges.append(E("ig", models[0]))
        edges.append(E(models[-1], "og"))
        edges.append(E("og", "ans", "ответ"))
    else:
        edges.append(E(models[-1], "ans", "ответ"))
    if has_wa:
        edges.append(E("og", "wa"))
    if full:
        items.append(N("obs", "6. Monitoring и observability: метрики, логи, traces, drift. Вокруг всей схемы",
                       0, 620, "db", 1420, 70))
        items.append(N("orch", "7. Orchestrator: определяет компоненты и порядок шагов (chaining)",
                       0, 710, "pu", 1420, 70))
    if step == 4:
        items.append(T("Gateway: единый API, каталог моделей,\nдоступ и ключи, лимиты, fallback, логи", 1180, 345, 16))
    return dict(items=items, edges=edges)


