def bars(prefix, vals, labels, x0, base, scale, bw=60, gap=20, kinds="p", fmt=str, lab_size=16, val_size=20):
    """Column chart from rectangles. kinds: one style key or a list (one per bar)."""
    items = []
    for i, (v, lab) in enumerate(zip(vals, labels)):
        x = x0 + i * (bw + gap)
        h = max(v * scale, 0)
        k = kinds[i] if isinstance(kinds, list) else kinds
        if h:
            items.append(N(f"{prefix}{i}", "", x, base - h, k, bw, h))
        s = fmt(v)
        items.append(T(s, x + bw / 2 - 5.5 * len(s), base - h - 30, val_size, GRAY))
        items.append(T(lab, x - 6, base + 10, lab_size, GRAY))
    return items


def stack(prefix, texts, x, y0, k, w, h, step):
    return [N(f"{prefix}{i}", t, x, y0 + i * step, k, w, h) for i, t in enumerate(texts)]


def chain(prefix, n):
    return [E(f"{prefix}{i}", f"{prefix}{i + 1}") for i in range(n - 1)]


